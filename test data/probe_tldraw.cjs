const {chromium}=require('playwright');
(async()=>{
const b=await chromium.launch({channel:'chrome',headless:true});
const c=await b.newContext({viewport:{width:1440,height:900},acceptDownloads:true});
const p=await c.newPage();
p.on('pageerror',e=>console.log('PAGEERROR',e.message.slice(0,200)));
await p.goto('https://www.tldraw.com/',{waitUntil:'domcontentloaded'});
await p.getByRole('button',{name:'Rectangle — R'}).waitFor({timeout:30000});
console.log('before shapes',await p.locator('[data-shape-id]').count());
await p.getByRole('button',{name:'Rectangle — R'}).click();
await p.mouse.move(500,300); await p.mouse.down(); await p.mouse.move(620,380,{steps:5}); await p.mouse.up();
await p.waitForTimeout(1500);
console.log('after shapes',await p.locator('[data-shape-id]').count());
console.log('local',await p.evaluate(()=>Object.fromEntries(Object.entries(localStorage).map(([k,v])=>[k,v.length]))));
await p.screenshot({path:'data/tldraw_probe.png'});
await p.reload({waitUntil:'domcontentloaded'}); await p.waitForTimeout(1500);
console.log('reload shapes',await p.locator('[data-shape-id]').count());
console.log('url',p.url());
await p.screenshot({path:'data/tldraw_probe_reload.png'});
await b.close();
})().catch(e=>{console.error(e);process.exitCode=1});
