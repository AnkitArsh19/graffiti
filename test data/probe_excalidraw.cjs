const {chromium}=require('playwright');
(async()=>{
const b=await chromium.launch({channel:'chrome',headless:true});
const c=await b.newContext({viewport:{width:1440,height:900},acceptDownloads:true});
const p=await c.newPage();
p.on('pageerror',e=>console.log('PAGEERROR',e.message));
await p.goto('https://excalidraw.com/',{waitUntil:'domcontentloaded'});
await p.getByRole('button',{name:'Rectangle',exact:true}).waitFor({timeout:30000});
console.log('canvas',await p.locator('canvas').evaluateAll(nodes=>nodes.map(n=>({cls:n.className,rect:n.getBoundingClientRect().toJSON()}))));
console.log('before',await p.evaluate(()=>Object.fromEntries(Object.entries(localStorage).map(([k,v])=>[k,v.length]))));
await p.getByRole('button',{name:'Rectangle',exact:true}).click();
await p.mouse.move(500,300); await p.mouse.down(); await p.mouse.move(620,380,{steps:5}); await p.mouse.up();
await p.waitForTimeout(1500);
console.log('after',await p.evaluate(()=>Object.fromEntries(Object.entries(localStorage).map(([k,v])=>[k,v.length]))));
await p.screenshot({path:'data/excalidraw_probe.png'});
await p.reload({waitUntil:'domcontentloaded'}); await p.waitForTimeout(1200);
console.log('reload',await p.evaluate(()=>Object.fromEntries(Object.entries(localStorage).map(([k,v])=>[k,v.length]))));
console.log('scene',await p.evaluate(()=>{const v=JSON.parse(localStorage.getItem('excalidraw'));return {array:Array.isArray(v),length:v.length,type:v[0]?.type}}));
console.log('undo',await p.getByRole('button',{name:'Undo',exact:true}).isEnabled());
await p.screenshot({path:'data/excalidraw_probe_reload.png'});
await b.close();
})().catch(e=>{console.error(e);process.exitCode=1});
